import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {PGlite} from '@electric-sql/pglite';

const read=path=>readFileSync(new URL(path,import.meta.url),'utf8');
const migration=read('../supabase/migrations/20261103112518_english_game_content.sql');

test('English and Turkish rooms share one authoritative puzzle language, including answers, social questions, math and songs',async()=>{
 const db=new PGlite();
 try{
  await db.exec(read('./fixtures/gameplay-schema.sql'));
  await db.exec(read('./fixtures/localization-schema.sql'));
  await db.exec(migration);
  const [{id:host}]=(await db.query('insert into auth.users values(gen_random_uuid()) returning id')).rows;
  const [{id:guest}]=(await db.query('insert into auth.users values(gen_random_uuid()) returning id')).rows;
  await db.query("select set_config('request.jwt.claim.sub',$1,false)",[host]);
  const [{result}]=(await db.query("select create_room_localized('Host','long','en') result")).rows;
  const room=result.room_id;
  assert.equal((await db.query('select game_language from rooms where id=$1',[room])).rows[0].game_language,'en');
  const listed=(await db.query('select * from list_open_rooms_localized() where code=$1',[result.code])).rows[0];
  assert.equal(listed.game_language,'en');
  await db.query("select set_config('request.jwt.claim.sub',$1,false)",[guest]);
  await assert.rejects(db.query("select set_room_game_language($1,'tr')",[room]),/not_host/);
  await db.query("select set_config('request.jwt.claim.sub',$1,false)",[host]);
  await db.query("select set_room_game_language($1,'tr')",[room]);
  await db.query("select set_room_game_language($1,'en')",[room]);
  await assert.rejects(db.query("select set_room_game_language($1,'de')",[room]),/invalid_language/);
  await db.query("insert into players(room_id,user_id,nickname,team_side) values($1,$2,'Guest','B')",[room,guest]);
  await db.query("update players set team_side='A' where room_id=$1 and is_host",[room]);
  await db.query("update rooms set phase='team_reveal',selected_games=array['anagram','riddle'] where id=$1",[room]);
  await assert.rejects(db.query("select set_room_game_language($1,'tr')",[room]),/language_locked/);
  await db.query('select start_game($1)',[room]);
  const rounds=(await db.query('select r.prompt,r.hints,q.language,q.answer,q.kind from room_rounds r join questions q on q.id=r.question_id where r.room_id=$1 order by r.idx',[room])).rows;
  assert.equal(rounds.length,20);
  assert.ok(rounds.every(r=>r.language==='en'));
  assert.equal(rounds.filter(r=>r.kind==='anagram').length,8);
  for(const r of rounds.filter(r=>r.kind==='anagram'))assert.equal([...r.prompt].sort().join(''),[...r.answer].sort().join(''));
  const checks=(await db.query("select answer,_is_correct(id,upper(answer)) ok,_is_correct(id,'not the answer') wrong from questions where language='en' and answer is not null")).rows;
  assert.ok(checks.every(q=>q.ok===true&&q.wrong===false));
  assert.equal((await db.query("select _is_correct(id,'Da Vinci!') ok from questions where language='en' and answer='leonardo da vinci'")).rows[0].ok,true);
  await db.query("update rooms set selected_games=array['social_guess'] where id=$1",[room]);
  await db.query('select _start_minigame($1)',[room]);
  assert.equal((await db.query("select count(*)::int n from room_minigames m join questions q on q.prompt=m.prompt where m.room_id=$1 and q.language='en'",[room])).rows[0].n,1);
  await db.query("update rooms set selected_games=array['math_guess'] where id=$1",[room]);
  await db.query('select _start_minigame($1)',[room]);
  const math=(await db.query("select * from room_minigames where room_id=$1 and kind='math_guess'",[room])).rows[0];
  assert.ok(!/[çğıöşüÇĞİÖŞÜ]/.test(math.prompt));
  await db.query('select configure_math_questions($1,5)',[math.id]);
  await db.query("update room_minigames set status='done' where id=$1",[math.id]);
  assert.equal((await db.query('select _start_math_followup($1) ok',[math.id])).rows[0].ok,true);
  const next=(await db.query("select * from room_minigames where room_id=$1 and kind='math_guess' and id<>$2",[room,math.id])).rows[0];
  assert.ok(!/[çğıöşüÇĞİÖŞÜ]/.test(next.prompt));
  assert.notEqual(next.prompt,math.prompt);
  assert.equal(next.math_state.index,2);
  await db.query("update rooms set selected_games=array['song_complete'] where id=$1",[room]);
  await db.query('select _start_minigame($1)',[room]);
  const song=(await db.query("select m.prompt,s.answer from room_minigames m join song_game_secrets s on s.minigame_id=m.id where m.room_id=$1",[room])).rows[0];
  assert.ok(song.prompt.includes('Complete the song title:'));
  assert.ok((await db.query("select 1 from song_questions where language='en' and title=$1",[song.answer])).rows.length);
  const legacy=(await db.query("select create_room('Legacy','quick') result")).rows[0].result;
  assert.equal((await db.query('select game_language from rooms where id=$1',[legacy.room_id])).rows[0].game_language,'tr');
  await db.query("update players set team_side='A' where room_id=$1",[legacy.room_id]);
  await db.query("update rooms set phase='team_reveal',selected_games=array['anagram','riddle'] where id=$1",[legacy.room_id]);
  await db.query('select start_game($1)',[legacy.room_id]);
  assert.ok((await db.query('select q.language from room_rounds r join questions q on q.id=r.question_id where r.room_id=$1',[legacy.room_id])).rows.every(r=>r.language==='tr'));
  await db.query("select set_config('request.jwt.claim.sub','',false)");
  await assert.rejects(db.query("select create_room_localized('No session','quick','en')"),/not_authenticated/);
  assert.equal((await db.query("select has_function_privilege('anon','public.create_room_localized(text,game_mode,text)','execute') ok")).rows[0].ok,false);
  assert.equal((await db.query("select has_function_privilege('authenticated','public._english_math_prompt(text)','execute') ok")).rows[0].ok,false);
  const before=(await db.query("select count(*)::int n from questions where language='en'")).rows[0].n;
  await db.exec(migration);
  assert.equal((await db.query("select count(*)::int n from questions where language='en'")).rows[0].n,before);
 }finally{await db.close();}
});
